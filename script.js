let youSlots = [null, null, null, null];
let themSlots = [null, null, null, null];
let activeSlotTarget = { side: "you", index: 0 };

function renderTradeSlots() {
  const youContainer = document.getElementById("you-slots");
  const themContainer = document.getElementById("them-slots");
  if (!youContainer || !themContainer) return;
  youContainer.innerHTML = "";
  themContainer.innerHTML = "";

  ["you", "them"].forEach(side => {
    const arr = side === "you" ? youSlots : themSlots;
    const container = side === "you" ? youContainer : themContainer;

    arr.forEach((item, idx) => {
      const slot = document.createElement("div");
      const isSelected = activeSlotTarget.side === side && activeSlotTarget.index === idx;
      slot.className = `trade-slot ${item ? "filled" : ""} ${isSelected ? "selected-target" : ""}`;

      if (item) {
        slot.innerHTML = `
          <div class="slot-fruit-art" style="background:${item.bg}">${item.icon}</div>
          <div class="slot-name">${item.name}</div>
          <div class="slot-val">${formatValue(item.value)}</div>
        `;
      } else {
        slot.innerHTML = `<span style="color:#64748b;font-size:1.3rem">+</span><small style="color:#64748b">Empty</small>`;
      }

      slot.addEventListener("click", () => {
        if (item) {
          arr[idx] = null;
        }
        activeSlotTarget = { side, index: idx };
        const pickerLbl = document.getElementById("picking-for-label");
        if (pickerLbl) {
          pickerLbl.textContent = `Adding to: ${side.toUpperCase()} — Slot #${idx + 1}`;
        }
        renderTradeSlots();
      });

      container.appendChild(slot);
    });
  });

  recalculateTrade();
}

function recalculateTrade() {
  const youVal = youSlots.reduce((s, i) => s + (i ? i.value : 0), 0);
  const themVal = themSlots.reduce((s, i) => s + (i ? i.value : 0), 0);

  const youBeli = youSlots.reduce((s, i) => s + (i ? i.beli : 0), 0);
  const themBeli = themSlots.reduce((s, i) => s + (i ? i.beli : 0), 0);

  const youTotValEl = document.getElementById("you-total-val");
  const themTotValEl = document.getElementById("them-total-val");
  const youBeliEl = document.getElementById("you-beli-val");
  const themBeliEl = document.getElementById("them-beli-val");

  if (youTotValEl) youTotValEl.textContent = `Value: ${formatValue(youVal)}`;
  if (themTotValEl) themTotValEl.textContent = `Value: ${formatValue(themVal)}`;
  if (youBeliEl) youBeliEl.textContent = `$${youBeli.toLocaleString()}`;
  if (themBeliEl) themBeliEl.textContent = `$${themBeli.toLocaleString()}`;

  const maxBeli = Math.max(youBeli, themBeli);
  const diffPct = maxBeli === 0 ? 0 : Math.round((Math.abs(youBeli - themBeli) / maxBeli) * 100);
  const hasPermOrGP = [...youSlots, ...themSlots].some(i => i && (i.cat === "Permanent" || i.cat === "Gamepass"));

  const diffEl = document.getElementById("price-diff-pct");
  const statusBadge = document.getElementById("trade-status-badge");
  if (diffEl) diffEl.textContent = `${diffPct}%`;

  if (statusBadge) {
    if (diffPct > 40 && !hasPermOrGP) {
      if (diffEl) diffEl.style.color = "#f87171";
      statusBadge.textContent = "PRICE DIFFERENCE > 40% (BLOCKED)";
      statusBadge.className = "trade-invalid";
    } else {
      if (diffEl) diffEl.style.color = "#4ade80";
      statusBadge.textContent = "VALID IN-GAME TRADE";
      statusBadge.className = "trade-fair";
    }
  }

  const verdictEl = document.getElementById("trade-verdict");
  if (verdictEl) {
    if (youVal === 0 && themVal === 0) {
      verdictEl.textContent = "FAIR";
      verdictEl.className = "verdict-fair";
    } else if (themVal > youVal * 1.08) {
      verdictEl.textContent = "BIG WIN (W)";
      verdictEl.className = "verdict-win";
    } else if (youVal > themVal * 1.08) {
      verdictEl.textContent = "LOSE (L)";
      verdictEl.className = "verdict-lose";
    } else {
      verdictEl.textContent = "FAIR (F)";
      verdictEl.className = "verdict-fair";
    }
  }
}

function renderTradePicker() {
  const searchInput = document.getElementById("trade-search-input");
  const strip = document.getElementById("trade-picker-list");
  if (!strip || !searchInput) return;
  const q = searchInput.value.toLowerCase().trim();
  strip.innerHTML = "";

  BLOX_ITEMS.filter(i => i.name.toLowerCase().includes(q) || i.cat.toLowerCase().includes(q)).forEach(item => {
    const chip = document.createElement("div");
    chip.className = "picker-chip";
    chip.innerHTML = `
      <span>${item.icon}</span>
      <div>
        <div style="font-weight:700;font-size:0.82rem">${item.name}</div>
        <div style="color:#4ade80;font-size:0.72rem">${formatValue(item.value)}</div>
      </div>
    `;
    chip.addEventListener("click", () => {
      const targetArr = activeSlotTarget.side === "you" ? youSlots : themSlots;
      targetArr[activeSlotTarget.index] = item;
      const nextEmpty = targetArr.findIndex(s => s === null);
      if (nextEmpty !== -1) activeSlotTarget.index = nextEmpty;
      renderTradeSlots();
    });
    strip.appendChild(chip);
  });
}

